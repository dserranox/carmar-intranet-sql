-- =======================
--  SABANAS DE CORTE (cabecera)
-- =======================
CREATE TABLE IF NOT EXISTS SABANAS_CORTE (
  SAB_ID BIGSERIAL PRIMARY KEY,
  SAB_NOMBRE VARCHAR(255) NOT NULL,
  SAB_ARCHIVO VARCHAR(255),
  SAB_USR_ID BIGINT REFERENCES USUARIOS(USR_ID) ON UPDATE CASCADE ON DELETE SET NULL,
  SAB_NRO_MAQUINA INT,
  SAB_ESTADO VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
  SAB_FECHA_INICIO TIMESTAMP,
  SAB_FECHA_FIN TIMESTAMP,
  -- Tolerancia del control de longitud, en porcentaje sobre la longitud nominal
  SAB_TOLERANCIA_INF NUMERIC(6,3) NOT NULL DEFAULT 0.000,
  SAB_TOLERANCIA_SUP NUMERIC(6,3) NOT NULL DEFAULT 0.200,
  SAB_OBSERVACIONES VARCHAR(1000),
  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_sab_usr    ON SABANAS_CORTE(SAB_USR_ID);
CREATE INDEX IF NOT EXISTS ix_sab_estado ON SABANAS_CORTE(SAB_ESTADO);

-- =======================
--  SABANAS DE CORTE (detalle: un renglón = un corte)
-- =======================
CREATE TABLE IF NOT EXISTS SABANAS_CORTE_DET (
  SCD_ID BIGSERIAL PRIMARY KEY,
  SCD_SAB_ID BIGINT NOT NULL REFERENCES SABANAS_CORTE(SAB_ID) ON UPDATE CASCADE ON DELETE CASCADE,
  SCD_NRO_CORTE INT NOT NULL,
  SCD_NRO_PLAN VARCHAR(64) NOT NULL,
  SCD_ORD_ID BIGINT REFERENCES ORDENES(ORD_ID) ON UPDATE CASCADE ON DELETE SET NULL,
  SCD_CODIGO VARCHAR(64) NOT NULL,
  SCD_CANTIDAD INT,
  SCD_NRO_CABLE VARCHAR(16),
  SCD_COLOR VARCHAR(64),
  SCD_SECCION NUMERIC(6,2),
  SCD_ORIGEN_A VARCHAR(64),
  SCD_TERMINAL_A VARCHAR(64),
  SCD_PELADO_A NUMERIC(8,2),
  SCD_GAP_A NUMERIC(8,2),
  SCD_LONGITUD NUMERIC(10,2) NOT NULL,
  SCD_GAP_B NUMERIC(8,2),
  SCD_PELADO_B NUMERIC(8,2),
  SCD_TERMINAL_B VARCHAR(64),
  SCD_DESTINO_B VARCHAR(64),
  SCD_IMPRESION VARCHAR(128),
  -- Avisos calculados en la importación, según el orden de la sábana
  SCD_CAMBIO_BOBINA BOOLEAN NOT NULL DEFAULT FALSE,
  SCD_CAMBIO_TERMINAL BOOLEAN NOT NULL DEFAULT FALSE,
  SCD_REQ_CTRL_LONGITUD BOOLEAN NOT NULL DEFAULT FALSE,
  SCD_REQ_CTRL_TRACCION_A BOOLEAN NOT NULL DEFAULT FALSE,
  SCD_REQ_CTRL_TRACCION_B BOOLEAN NOT NULL DEFAULT FALSE,
  -- Ejecución
  SCD_ESTADO VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
  SCD_FECHA_INICIO TIMESTAMP,
  SCD_FECHA_FIN TIMESTAMP,
  SCD_SEGUNDOS INT,
  SCD_NO_CONFORME INT,
  SCD_OBSERVACIONES VARCHAR(1000),
  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_scd_sabana_corte ON SABANAS_CORTE_DET(SCD_SAB_ID, SCD_NRO_CORTE);
CREATE INDEX IF NOT EXISTS ix_scd_sabana ON SABANAS_CORTE_DET(SCD_SAB_ID);
CREATE INDEX IF NOT EXISTS ix_scd_orden  ON SABANAS_CORTE_DET(SCD_ORD_ID);
CREATE INDEX IF NOT EXISTS ix_scd_estado ON SABANAS_CORTE_DET(SCD_SAB_ID, SCD_ESTADO);

-- =======================
--  CONTROLES DE CALIDAD
-- =======================
CREATE TABLE IF NOT EXISTS CONTROLES_CALIDAD (
  CCA_ID BIGSERIAL PRIMARY KEY,
  CCA_SCD_ID BIGINT NOT NULL REFERENCES SABANAS_CORTE_DET(SCD_ID) ON UPDATE CASCADE ON DELETE CASCADE,
  CCA_TIPO VARCHAR(20) NOT NULL,             -- LONGITUD | TRACCION
  CCA_EXTREMO VARCHAR(1),                    -- A | B (sólo tracción)
  CCA_VALOR_NOMINAL NUMERIC(10,2),           -- longitud teórica (mm) o fuerza mínima exigida (N)
  CCA_VALOR_MEDIDO NUMERIC(10,2) NOT NULL,   -- longitud medida (mm) o fuerza obtenida (N)
  CCA_VALOR_MIN NUMERIC(10,2),
  CCA_VALOR_MAX NUMERIC(10,2),
  CCA_RESULTADO VARCHAR(10) NOT NULL,        -- OK | NO_OK
  CCA_SECCION NUMERIC(6,2),
  CCA_TERMINAL VARCHAR(64),
  CCA_OBSERVACIONES VARCHAR(500),
  CCA_USR_ID BIGINT NOT NULL REFERENCES USUARIOS(USR_ID) ON UPDATE CASCADE ON DELETE CASCADE,
  CCA_FECHA TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_cca_corte ON CONTROLES_CALIDAD(CCA_SCD_ID);
CREATE INDEX IF NOT EXISTS ix_cca_tipo  ON CONTROLES_CALIDAD(CCA_TIPO, CCA_FECHA);

-- =======================
--  FUERZA MÍNIMA DE TRACCIÓN POR SECCIÓN
--  Valores orientativos IEC 60352-2 / USCAR-21. El administrador los ajusta.
-- =======================
CREATE TABLE IF NOT EXISTS TRACCION_MINIMA (
  TRM_ID BIGSERIAL PRIMARY KEY,
  TRM_SECCION NUMERIC(6,2) NOT NULL,
  TRM_FUERZA_MIN NUMERIC(8,2) NOT NULL,      -- Newtons
  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_trm_seccion ON TRACCION_MINIMA(TRM_SECCION);

INSERT INTO TRACCION_MINIMA (TRM_SECCION, TRM_FUERZA_MIN, aud_usr_ins, aud_usr_upd)
SELECT v.seccion, v.fuerza, 'auto', 'auto'
FROM (VALUES
  (0.35, 60.0), (0.50, 85.0), (0.75, 120.0), (1.00, 150.0),
  (1.50, 200.0), (2.50, 300.0), (4.00, 400.0), (6.00, 500.0)
) AS v(seccion, fuerza)
WHERE NOT EXISTS (SELECT 1 FROM TRACCION_MINIMA t WHERE t.TRM_SECCION = v.seccion);

