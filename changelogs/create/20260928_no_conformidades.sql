INSERT INTO PERMISOS (PRM_CLAVE, PRM_DESCRIPCION) VALUES
  ('NOCONFORMIDADES:READ',  'Ver las no conformidades'),
  ('NOCONFORMIDADES:WRITE', 'Abrir, editar y cerrar no conformidades')
ON CONFLICT (PRM_CLAVE) DO NOTHING;

-- Las abren calidad y el jefe de producción; el admin también.
INSERT INTO ROLES_PERMISOS (RP_ROL_ID, RP_PRM_ID)
SELECT r.ROL_ID, p.PRM_ID
FROM ROLES r, PERMISOS p
WHERE r.ROL_NOMBRE IN ('ADMIN', 'CALIDAD', 'JEFE_PRODUCCION')
  AND p.PRM_CLAVE IN ('NOCONFORMIDADES:READ', 'NOCONFORMIDADES:WRITE')
  AND NOT EXISTS (
    SELECT 1 FROM ROLES_PERMISOS rp WHERE rp.RP_ROL_ID = r.ROL_ID AND rp.RP_PRM_ID = p.PRM_ID);

