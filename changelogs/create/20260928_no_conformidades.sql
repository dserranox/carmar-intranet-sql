-- =======================
--  NO CONFORMIDADES
--  Registro de desvíos según el formulario FQ-02 que usan para la ISO.
--  Las abren calidad o el jefe de producción, y pueden nacer de un KO de la
--  recorrida, de un control de corte, del muro de calidad, etc.
-- =======================

-- Vienen numerando en papel: la próxima que carguen es la 54.
CREATE SEQUENCE IF NOT EXISTS SEQ_NO_CONFORMIDAD START WITH 54 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS NO_CONFORMIDADES (
  NCF_ID BIGSERIAL PRIMARY KEY,
  NCF_NUMERO INT NOT NULL UNIQUE,
  NCF_TIPO VARCHAR(10) NOT NULL,                 -- INTERNA | EXTERNA
  NCF_FECHA_EMISION DATE NOT NULL DEFAULT CURRENT_DATE,

  -- A quién se le emite
  NCF_EMITIDA_A VARCHAR(20) NOT NULL,            -- PRODUCCION | OTRO
  NCF_EMITIDA_A_OTRO VARCHAR(160),

  -- Quién la emite
  NCF_EMITE VARCHAR(20) NOT NULL,                -- CALIDAD | CLIENTE | OTRO
  NCF_EMITE_CLI_ID BIGINT REFERENCES CLIENTES(CLI_ID) ON UPDATE CASCADE ON DELETE SET NULL,
  NCF_EMITE_OTRO VARCHAR(160),

  -- Dónde se detectó
  NCF_ORIGEN VARCHAR(30) NOT NULL,               -- AUDITORIA_INTERNA | RUTA_CONTROL | MURO_CALIDAD |
                                                 -- CONTROL_RECEPCION | AUTOCONTROL | OTRO_INTERNO |
                                                 -- DETECTADA_CLIENTE | OTRO_EXTERNO
  NCF_ORIGEN_OTRO VARCHAR(200),

  -- Los cinco puntos del formulario
  NCF_DESCRIPCION VARCHAR(4000) NOT NULL,
  NCF_ACCION_INMEDIATA VARCHAR(4000),
  NCF_ANALISIS_CAUSAS VARCHAR(4000),
  NCF_ACCION_CORRECTIVA VARCHAR(4000),
  NCF_VERIFICACION_EFICACIA VARCHAR(4000),
  NCF_OBSERVACIONES VARCHAR(2000),

  NCF_EJECUCION VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',  -- PENDIENTE | EJECUTADA | NO_EJECUTADA
  NCF_FECHA_VERIFICACION DATE,

  NCF_ESTADO VARCHAR(10) NOT NULL DEFAULT 'ABIERTA',       -- ABIERTA | CERRADA
  NCF_FECHA_CIERRE TIMESTAMP,
  NCF_USR_CIERRE_ID BIGINT REFERENCES USUARIOS(USR_ID) ON UPDATE CASCADE ON DELETE SET NULL,

  -- Trazabilidad: de dónde salió, para poder volver al hecho concreto
  NCF_ORD_ID BIGINT REFERENCES ORDENES(ORD_ID) ON UPDATE CASCADE ON DELETE SET NULL,
  NCF_NRO_PLAN VARCHAR(64),
  NCF_PRODUCTO_CODIGO VARCHAR(64),
  NCF_PRODUCTO_DESCRIPCION VARCHAR(255),
  NCF_RCC_ID BIGINT REFERENCES RUTAS_CALIDAD_CONTROLES(RCC_ID) ON UPDATE CASCADE ON DELETE SET NULL,
  NCF_CCA_ID BIGINT REFERENCES CONTROLES_CALIDAD(CCA_ID) ON UPDATE CASCADE ON DELETE SET NULL,
  NCF_OPERARIO VARCHAR(64),
  NCF_PUESTO VARCHAR(64),

  NCF_USR_ID BIGINT NOT NULL REFERENCES USUARIOS(USR_ID) ON UPDATE CASCADE ON DELETE CASCADE,
  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_ncf_estado ON NO_CONFORMIDADES(NCF_ESTADO, NCF_FECHA_EMISION DESC);
CREATE INDEX IF NOT EXISTS ix_ncf_origen ON NO_CONFORMIDADES(NCF_ORIGEN);
CREATE INDEX IF NOT EXISTS ix_ncf_rcc    ON NO_CONFORMIDADES(NCF_RCC_ID);

-- Puede haber más de un responsable de las acciones.
CREATE TABLE IF NOT EXISTS NO_CONFORMIDADES_RESPONSABLES (
  NCR_ID BIGSERIAL PRIMARY KEY,
  NCR_NCF_ID BIGINT NOT NULL REFERENCES NO_CONFORMIDADES(NCF_ID) ON UPDATE CASCADE ON DELETE CASCADE,
  NCR_USR_ID BIGINT NOT NULL REFERENCES USUARIOS(USR_ID) ON UPDATE CASCADE ON DELETE CASCADE,
  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_ncr_nc_usuario ON NO_CONFORMIDADES_RESPONSABLES(NCR_NCF_ID, NCR_USR_ID);

-- Fotos del desvío, sacadas con la tablet. Se guardan acá para no depender de
-- ninguna carpeta ni servicio externo.
CREATE TABLE IF NOT EXISTS NO_CONFORMIDADES_ADJUNTOS (
  NCA_ID BIGSERIAL PRIMARY KEY,
  NCA_NCF_ID BIGINT NOT NULL REFERENCES NO_CONFORMIDADES(NCF_ID) ON UPDATE CASCADE ON DELETE CASCADE,
  NCA_NOMBRE VARCHAR(255) NOT NULL,
  NCA_TIPO VARCHAR(100) NOT NULL,
  NCA_TAMANIO BIGINT NOT NULL,
  NCA_CONTENIDO BYTEA NOT NULL,
  NCA_DESCRIPCION VARCHAR(255),
  NCA_FECHA TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_nca_nc ON NO_CONFORMIDADES_ADJUNTOS(NCA_NCF_ID);

