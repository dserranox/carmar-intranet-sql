-- =======================
--  La asignación pasa a ser de un CÓDIGO (orden) a un operario, con VARIAS
--  actividades adentro. El operario arranca y termina actividades las veces que
--  haga falta (monta, crimpea, vuelve a montar, controla) y recién cuando avisa
--  que terminó se libera el código siguiente de su cola.
-- =======================
CREATE TABLE IF NOT EXISTS ASIGNACION_ACTIVIDADES (
  AAC_ID BIGSERIAL PRIMARY KEY,
  AAC_ASG_ID BIGINT NOT NULL REFERENCES ASIGNACIONES(ASG_ID) ON UPDATE CASCADE ON DELETE CASCADE,
  AAC_OPE_ID BIGINT NOT NULL REFERENCES OPERACIONES(OPE_ID) ON UPDATE CASCADE ON DELETE CASCADE,
  AAC_CANTIDAD INT,
  AAC_NRO_MAQUINA INT,
  AAC_PUESTO VARCHAR(64),
  AAC_ORDEN INT,
  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_aac_asignacion ON ASIGNACION_ACTIVIDADES(AAC_ASG_ID);

-- Las asignaciones que ya existían (una por actividad) pasan a ser su propia
-- cabecera con una sola actividad adentro.
INSERT INTO ASIGNACION_ACTIVIDADES
  (AAC_ASG_ID, AAC_OPE_ID, AAC_CANTIDAD, AAC_NRO_MAQUINA, AAC_PUESTO, AAC_ORDEN, aud_usr_ins, aud_usr_upd)
SELECT a.ASG_ID, a.ASG_OPE_ID, a.ASG_CANTIDAD, a.ASG_NRO_MAQUINA, a.ASG_PUESTO, 1, 'migracion', 'migracion'
FROM ASIGNACIONES a
WHERE NOT EXISTS (SELECT 1 FROM ASIGNACION_ACTIVIDADES d WHERE d.AAC_ASG_ID = a.ASG_ID);

ALTER TABLE ASIGNACIONES DROP COLUMN IF EXISTS ASG_OPE_ID;
ALTER TABLE ASIGNACIONES DROP COLUMN IF EXISTS ASG_TAR_ID;

-- Una asignación también se puede suspender para retomarla después.
ALTER TABLE ASIGNACIONES ADD COLUMN IF NOT EXISTS ASG_FECHA_SUSPENSION TIMESTAMP;
ALTER TABLE ASIGNACIONES ADD COLUMN IF NOT EXISTS ASG_SUBTIPO_SUSPENSION VARCHAR(30);
ALTER TABLE ASIGNACIONES ADD COLUMN IF NOT EXISTS ASG_MOTIVO_SUSPENSION VARCHAR(500);

COMMENT ON COLUMN ASIGNACIONES.ASG_ESTADO IS
  'PENDIENTE | EN_CURSO | SUSPENDIDA | FINALIZADA | CANCELADA';

-- Cada tarea sabe de qué asignación y de qué actividad salió: una asignación
-- puede generar muchas tareas.
ALTER TABLE TAREAS ADD COLUMN IF NOT EXISTS TAR_ASG_ID BIGINT
  REFERENCES ASIGNACIONES(ASG_ID) ON UPDATE CASCADE ON DELETE SET NULL;
ALTER TABLE TAREAS ADD COLUMN IF NOT EXISTS TAR_AAC_ID BIGINT
  REFERENCES ASIGNACION_ACTIVIDADES(AAC_ID) ON UPDATE CASCADE ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS ix_tar_asignacion ON TAREAS(TAR_ASG_ID);

-- =======================
--  EVENTOS DE TRABAJO: pausas y suspensiones de una asignación, igual que en corte.
-- =======================
CREATE TABLE IF NOT EXISTS EVENTOS_TRABAJO (
  EVT_ID BIGSERIAL PRIMARY KEY,
  EVT_ASG_ID BIGINT NOT NULL REFERENCES ASIGNACIONES(ASG_ID) ON UPDATE CASCADE ON DELETE CASCADE,
  EVT_TAR_ID BIGINT REFERENCES TAREAS(TAR_ID) ON UPDATE CASCADE ON DELETE SET NULL,
  EVT_TIPO VARCHAR(20) NOT NULL,      -- PAUSA | SUSPENSION
  EVT_SUBTIPO VARCHAR(30) NOT NULL,   -- PAUSA: CONSULTA_TECNICA | CONSULTA_CALIDAD | FALTA_MATERIAL |
                                      --        MANTENIMIENTO | DESCANSO | OTROS
                                      -- SUSPENSION: FIN_JORNADA | OTRA_TAREA | OTROS
  EVT_MOTIVO VARCHAR(500),
  EVT_FECHA_INICIO TIMESTAMP NOT NULL,
  EVT_FECHA_FIN TIMESTAMP NOT NULL,
  EVT_SEGUNDOS INT NOT NULL,
  EVT_USR_ID BIGINT NOT NULL REFERENCES USUARIOS(USR_ID) ON UPDATE CASCADE ON DELETE CASCADE,
  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_evt_asignacion ON EVENTOS_TRABAJO(EVT_ASG_ID);
CREATE INDEX IF NOT EXISTS ix_evt_tarea ON EVENTOS_TRABAJO(EVT_TAR_ID);
